// Bytes to and from base64, the way they travel in JSON. (Works in browsers,
// Node and the phone's JavaScript, none of which agree on a built-in way.)

export function fromBytes(bytes: Uint8Array): string {
  let text = '';
  for (let i = 0; i < bytes.length; i += 0x8000) text += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(text);
}

/** Throws on anything that isn't base64. */
export function toBytes(b64: string): Uint8Array {
  const text = atob(b64);
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) out[i] = text.charCodeAt(i);
  return out;
}

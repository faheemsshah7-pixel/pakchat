/** Fills {name}-style gaps: fill('{n} members', { n: 3 }) → '3 members'. */
export function fill(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ''));
}

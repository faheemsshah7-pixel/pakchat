/** A country's flag, made from its two letters (the phone draws it). */
export function flag(code: string) {
  return String.fromCodePoint(...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

/**
 * The full number ("+923001234567") from the country and what was typed, or a reason it
 * can't be one. People in Pakistan often type the 0 in front ("0300 …"), so it's dropped.
 */
export function fullNumber(country: Country, typed: string): { phone: string } | { problem: 'bad' | 'pkMobile' } {
  let digits = typed.replace(/\D/g, '');
  // Typed with the country code already ("92300…" or "+92 300…" pasted in): keep it once.
  if (typed.trim().startsWith('+') && digits.startsWith(country.dial)) digits = digits.slice(country.dial.length);
  digits = digits.replace(/^0+/, '');
  if (country.code === 'PK') {
    if (digits.length === 12 && digits.startsWith('92')) digits = digits.slice(2);
    // Pakistani mobiles: 3xx and 7 more digits.
    if (!/^3\d{9}$/.test(digits)) return { problem: 'pkMobile' };
  } else if (digits.length < 6 || country.dial.length + digits.length > 15) {
    return { problem: 'bad' };
  }
  return { phone: `+${country.dial}${digits}` };
}

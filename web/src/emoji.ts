const RECENT_KEY = 'recentEmojis'

export function recentEmojis(): string[] {
  try {
    return JSON.parse(localStorage.getItem(RECENT_KEY) ?? '[]')
  } catch {
    return []
  }
}

export function rememberEmoji(emoji: string) {
  try {
    const recent = [emoji, ...recentEmojis().filter((e) => e !== emoji)].slice(0, 24)
    localStorage.setItem(RECENT_KEY, JSON.stringify(recent))
  } catch {
    // not remembered; that's fine
  }
}

// "Only emojis, and at most 3" -> shown big, like WhatsApp.
const EMOJI_ONLY = /^(?:\p{Extended_Pictographic}|\p{Emoji_Component}|\p{Regional_Indicator}|‍|️|\s)+$/u
export function isJumboEmoji(text: string) {
  if (!EMOJI_ONLY.test(text) || /^[\d\s#*]+$/.test(text)) return false
  const count = [...new Intl.Segmenter().segment(text.replace(/\s/g, ''))].length
  return count > 0 && count <= 3
}
